// INDEX.md: two views of the same set — newest first, for "what has been happening",
// and by area, for "where is the document about X". Generated, never maintained.
//
// The output carries no generation timestamp, on purpose: the same documents must give
// byte-identical output, so `check` can tell a stale index from a fresh one.

import { LIFECYCLES } from "./config.mjs";

export const MARK = {
  draft: "✏️",
  planned: "📋",
  "in-progress": "🔧",
  done: "✅",
  current: "📘",
  superseded: "🗑️",
  retired: "📦",
  abandoned: "⛔",
};

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const link = (d) => `[${esc(d.meta.title || d.id)}](${encodeURI(d.rel)})`;
const byUpdated = (a, b) =>
  String(b.meta.updated ?? "").localeCompare(String(a.meta.updated ?? "")) || a.id.localeCompare(b.id);
const byCreated = (a, b) =>
  String(b.meta.created ?? "").localeCompare(String(a.meta.created ?? "")) || a.id.localeCompare(b.id);

export function renderIndex(config, docs) {
  const legend = new Map();
  for (const lifecycle of Object.values(LIFECYCLES)) {
    for (const [status, text] of Object.entries(lifecycle)) if (!legend.has(status)) legend.set(status, text);
  }

  const lines = [
    `# ${config.title}`,
    "",
    `> Generated by \`${config.command} index\`. Do not edit — change the document's own frontmatter`,
    "> and run it again.",
    ">",
    "> **The code is the truth.** A document records what was decided at the time. Where the",
    "> two disagree, believe the code, then come back and correct the document's `status`.",
    "",
    `${docs.length} document${docs.length === 1 ? "" : "s"}`,
    "",
    "| | Status | Meaning |",
    "|---|---|---|",
    ...Object.keys(MARK).map((s) => `| ${MARK[s]} | ${s} | ${esc(legend.get(s))} |`),
    "",
  ];

  const recent = [...docs].sort(byUpdated).slice(0, config.recent);
  if (recent.length) {
    lines.push("## Recently changed", "", "| Updated | | Document | Area |", "|---|---|---|---|");
    for (const d of recent) {
      lines.push(`| ${esc(d.meta.updated)} | ${MARK[d.meta.status] ?? ""} | ${link(d)} | ${esc(d.meta.area)} |`);
    }
    lines.push("");
  }

  const areaNames = Object.keys(config.areas);
  const present = [...new Set(docs.map((d) => d.meta.area).filter(Boolean))].sort(
    (a, b) => (areaNames.indexOf(a) + 1 || 1e9) - (areaNames.indexOf(b) + 1 || 1e9) || a.localeCompare(b),
  );
  if (present.length) lines.push("## By area", "");
  for (const area of present) {
    lines.push(`### ${area}`, "");
    if (config.areas[area]) lines.push(`_${esc(config.areas[area])}_`, "");
    lines.push("| | Document | Type | Progress | Updated |", "|---|---|---|---|---|");
    for (const d of docs.filter((x) => x.meta.area === area).sort(byCreated)) {
      lines.push(
        `| ${MARK[d.meta.status] ?? ""} | ${link(d)} | ${esc(d.meta.type)} | ${esc(d.meta.progress)} | ${esc(d.meta.updated)} |`,
      );
    }
    lines.push("");
  }

  const loose = docs.filter((d) => !d.meta.area);
  if (loose.length) {
    lines.push("## Not filed yet", "", "| Document |", "|---|");
    for (const d of loose.sort((a, b) => a.id.localeCompare(b.id))) lines.push(`| ${link(d)} |`);
    lines.push("");
  }

  return lines.join("\n");
}
